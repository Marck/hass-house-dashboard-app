// Writes app/frontend/js/build-info.js for a build, so the dashboard can say
// which commit it is running. The image build runs this; values come from the
// environment, and the version from package.json, the one place it is written.
//
//   GIT_SHA=... GIT_TAG=... GIT_MODIFIED=false BUILD_CHANNEL=preview node scripts/build-info.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const CHANNELS = ['dev', 'preview', 'stable'];

/** Build information from environment values. Anything malformed becomes empty, never an error. */
export function fromEnv(env, version, today = new Date().toISOString().slice(0, 10)) {
  const sha = String(env.GIT_SHA || '');
  const tag = String(env.GIT_TAG || '');
  return {
    version,
    channel: CHANNELS.includes(env.BUILD_CHANNEL) ? env.BUILD_CHANNEL : 'preview',
    // Twelve characters are enough to match a commit and short enough to read on a wall.
    commit: /^[0-9a-f]{7,40}$/.test(sha) ? sha.slice(0, 12) : '',
    modified: env.GIT_MODIFIED === 'true',
    tag: /^v[\w.-]{1,40}$/.test(tag) ? tag : '',
    // The day, not the minute: the commit identifies a build, the date only places it.
    builtOn: /^\d{4}-\d{2}-\d{2}$/.test(env.BUILT_ON || '') ? env.BUILT_ON : today,
  };
}

export const moduleSource = (info) => `// Generated by scripts/build-info.mjs. Do not edit.\nexport const BUILD = ${JSON.stringify(info, null, 2)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL('..', import.meta.url);
  const { version } = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
  const info = fromEnv(process.env, version);
  writeFileSync(new URL('app/frontend/js/build-info.js', root), moduleSource(info));
  console.log(`build-info: ${info.version} ${info.channel} ${info.commit || 'no commit'}`);
}
